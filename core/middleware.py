"""Middleware de sécurité applicative (Content-Security-Policy)."""


class ContentSecurityPolicyMiddleware:
    """Ajoute une politique CSP stricte 'self' sur chaque réponse HTTP."""

    CSP_VALUE = (
        "default-src 'self'; "
        "script-src 'self'; "
        "style-src 'self'; "
        "img-src 'self' data:; "
        "font-src 'self'; "
        "connect-src 'self'; "
        "form-action 'self'; "
        "frame-ancestors 'none'; "
        "base-uri 'self'; "
        "object-src 'none'"
    )

    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request):
        response = self.get_response(request)
        if "Content-Security-Policy" not in response:
            response["Content-Security-Policy"] = self.CSP_VALUE
        return response
